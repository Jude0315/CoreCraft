const express =
  require("express");

const cors =
  require("cors");

const mongoose =
  require("mongoose");

const ProjectRoutes =
  require("./Routes/ProjectRoutes");
const TaskRoutes =
  require("./Routes/TaskRoutes");

const AuthRoutes =
  require("./Routes/AuthRoutes");

const LookupRoutes =
  require("./Routes/LookupRoutes");


const app =
  express();


app.use(cors());

app.use(
  express.json()
);


mongoose
  .connect(
    process.env.MONGO_URI
  )
  .then(() => {
    console.log(
      "MongoDB connected"
    );
  })
  .catch((error) => {
    console.error(
      "MongoDB connection error:",
      error.message
    );
  });


app.use(
  "/api/auth",
  AuthRoutes
);

app.use(
  "/api/lookups",
  LookupRoutes
);

app.use(
  "/api/project",
  ProjectRoutes
);
app.use(
  "/api/task",
  TaskRoutes
);


app.get(
  "/",
  (req, res) => {
    res.json({
      message:
        "Generated by CoreCraft",
    });
  }
);


module.exports =
  app;
