const GenerateServerAppFile = (
  specification = {}
) => {
  const entities =
    Array.isArray(
      specification.entities
    )
      ? specification.entities
      : [];

  const apiModules =
    Array.isArray(
      specification.apiModules
    )
      ? specification.apiModules
      : [];

  const roles =
    Array.isArray(
      specification.roles
    )
      ? specification.roles
      : [];

  const pages =
    Array.isArray(
      specification.pages
    )
      ? specification.pages
      : [];

  const hasAuthentication =
    roles.length > 0 ||
    pages.some(
      (page) =>
        page?.protected === true
    ) ||
    apiModules.some(
      (module) =>
        module?.protected === true
    );

  const hasLookups =
    entities.some(
      (entity) =>
        (entity.fields || [])
          .some(
            (field) =>
              field.type ===
                "ObjectId" &&
              field.ref
          )
    );

  /* -----------------------------------------
     Generate route imports dynamically
     ----------------------------------------- */

  const routeImports =
    entities
      .map((entity) => {
        const entityName =
          GetEntityName(entity);

        if (!entityName) {
          return "";
        }

        return `const ${entityName}Routes =
  require("./Routes/${entityName}Routes");`;
      })
      .filter(Boolean)
      .join("\n");


  /* -----------------------------------------
     Generate route registrations dynamically
     ----------------------------------------- */

  const routeRegistrations =
    entities
      .map((entity) => {
        const entityName =
          GetEntityName(entity);

        if (!entityName) {
          return "";
        }

        const routeName =
          entityName.toLowerCase();

        return `app.use(
  "/api/${routeName}",
  ${entityName}Routes
);`;
      })
      .filter(Boolean)
      .join("\n");


  /* -----------------------------------------
     Authentication route
     ----------------------------------------- */

  const authImport =
    hasAuthentication
      ? `const AuthRoutes =
  require("./Routes/AuthRoutes");`
      : "";

  const authRegistration =
    hasAuthentication
      ? `app.use(
  "/api/auth",
  AuthRoutes
);`
      : "";

  const lookupImport =
    hasLookups
      ? `const LookupRoutes =
  require("./Routes/LookupRoutes");`
      : "";

  const lookupRegistration =
    hasLookups
      ? `app.use(
  "/api/lookups",
  LookupRoutes
);`
      : "";


  return `const express =
  require("express");

const cors =
  require("cors");

const mongoose =
  require("mongoose");

${routeImports}

${authImport}

${lookupImport}


const app =
  express();


app.use(cors());

app.use(
  express.json()
);


mongoose
  .connect(
    process.env.MONGO_URI
  )
  .then(() => {
    console.log(
      "MongoDB connected"
    );
  })
  .catch((error) => {
    console.error(
      "MongoDB connection error:",
      error.message
    );
  });


${authRegistration}

${lookupRegistration}

${routeRegistrations}


app.get(
  "/",
  (req, res) => {
    res.json({
      message:
        "Generated by CoreCraft",
    });
  }
);


module.exports =
  app;
`;
};

