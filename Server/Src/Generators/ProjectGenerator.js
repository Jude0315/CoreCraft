const GenerateAppJsx = (
  pages = [],
  features = []
) => {
  const normalizedPages =
    pages.map((page) => ({
      page,
      componentName:
        NormalizeComponentName(page),
      route:
        CreateRoutePath(page),
    }));

  const pageImports =
    normalizedPages
      .map(
        ({ componentName }) =>
          `import ${componentName} from "./Pages/${componentName}";`
      )
      .join("\n");

  const hasAuthentication =
    features.some((feature) => {
      const normalized =
        feature.toLowerCase();

      return (
        normalized.includes("login") ||
        normalized.includes("auth") ||
        normalized.includes("register")
      );
    });

  const protectedRouteImport =
    hasAuthentication
      ? `import ProtectedRoute from "./Routes/ProtectedRoute";`
      : "";

  const navbarImport =
    hasAuthentication
      ? `import Navbar from "./Components/Navbar";`
      : "";

  const hasRegisterPage =
    normalizedPages.some(
      ({ componentName }) =>
        componentName === "RegisterPage"
    );

  const extraRegisterImport =
    hasAuthentication &&
    !hasRegisterPage
      ? `import RegisterPage from "./Pages/RegisterPage";`
      : "";

  const routeDefinitions =
    normalizedPages
      .map(
        ({
          page,
          componentName,
          route,
        }) => {
          const pageName =
            page.toLowerCase();

          const path =
            pageName === "home page"
              ? "/"
              : `/${route}`;

          const isLogin =
            componentName ===
            "LoginPage";

          const isRegister =
            componentName ===
            "RegisterPage";

          const isInstructorPortal =
            componentName ===
            "InstructorPortal";

          if (
            !hasAuthentication ||
            isLogin ||
            isRegister
          ) {
            return `        <Route path="${path}" element={<${componentName} />} />`;
          }

          if (
            pageName === "home page"
          ) {
            return `        <Route
          path="${path}"
          element={
            <>
              <Navbar />
              <${componentName} />
            </>
          }
        />`;
          }

          if (
            isInstructorPortal
          ) {
            return `        <Route
          path="${path}"
          element={
            <ProtectedRoute roles={["instructor", "admin"]}>
              <>
                <Navbar />
                <${componentName} />
              </>
            </ProtectedRoute>
          }
        />`;
          }

          return `        <Route
          path="${path}"
          element={
            <ProtectedRoute>
              <>
                <Navbar />
                <${componentName} />
              </>
            </ProtectedRoute>
          }
        />`;
        }
      )
      .join("\n");

  const registerRoute =
    hasAuthentication &&
    !hasRegisterPage
      ? `        <Route path="/register" element={<RegisterPage />} />`
      : "";

  return `import React from "react";

import {
  Routes,
  Route,
} from "react-router-dom";

${pageImports}

${protectedRouteImport}
${navbarImport}
${extraRegisterImport}

const App = () => {
  return (
    <Routes>
${routeDefinitions}

${registerRoute}
    </Routes>
  );
};

export default App;
`;
};

