const GenerateServerAppFile = (
  entities = [],
  features = []
) => {
  const routeImports = entities
    .map(
      (entity) =>
        `const ${entity}Routes = require("./Routes/${entity}Routes");`
    )
    .join("\n");

  const routeRegistrations = entities
    .map(
      (entity) =>
        `app.use("/api/${entity.toLowerCase()}", ${entity}Routes);`
    )
    .join("\n");

  const normalizedFeatures = features.map(
    (feature) => feature.toLowerCase()
  );

  const hasAuthentication =
    normalizedFeatures.some(
      (feature) =>
        feature.includes("login") ||
        feature.includes("auth") ||
        feature.includes("register")
    );

  const authImport = hasAuthentication
    ? `const AuthRoutes = require("./Routes/AuthRoutes");`
    : "";

  const authRegistration = hasAuthentication
    ? `app.use("/api/auth", AuthRoutes);`
    : "";

  return `const express = require("express");
const cors = require("cors");
const mongoose = require("mongoose");

${routeImports}
${authImport}

const app = express();

app.use(cors());
app.use(express.json());

mongoose
  .connect(process.env.MONGO_URI)
  .then(() => {
    console.log("MongoDB connected");
  })
  .catch((error) => {
    console.error(
      "MongoDB connection error:",
      error.message
    );
  });

${authRegistration}

${routeRegistrations}

app.get("/", (req, res) => {
  res.json({
    message: "Generated by CoreCraft",
  });
});

module.exports = app;
`;
};

